import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = file => readFileSync(new URL(file, import.meta.url), 'utf8')
const home = read('../src/pages/index.vue')
const notes = read('../src/pages/feathers.vue')
const shell = read('../src/components/ExampleShell.vue')
const style = read('../src/styles/main.css')
const guide = read('../../../.agents/skills/vevedh-full-web-stack-vite/references/ui-ux-pro-max-codeandchill.md')
for (const path of ['to="/"', 'to="/feathers"', 'aria-label="Navigation principale"'])
  assert.ok(shell.includes(path), `Missing accessible navigation: ${path}`)
assert.match(home, /<RouterLink[^>]*to="\/feathers"/)
assert.match(home, /<TheInput/)
assert.match(notes, /useNotesStore\(\)/)
assert.match(notes, /data-testid="socket-status"/)
assert.match(notes, /data-testid="health-status"/)
assert.match(notes, /data-testid="event-count"/)
assert.match(notes, /role="alert"/)
assert.doesNotMatch(notes, /socket\.emit\(/)
for (const token of ['--vf-surface', '--vf-primary', '--vf-text', '--vf-border']) assert.ok(style.includes(token))
assert.match(style, /html\.dark/)
assert.match(style, /prefers-reduced-motion/)
assert.match(style, /@media\(max-width:600px\)/)
assert.match(guide, /codeandchill\.store/)
assert.match(guide, /ui-ux-pro-max-skill/)
for (const source of [home, notes, shell, style]) {
  assert.doesNotMatch(source, /<script[^>]+src="https?:\/\//)
  assert.doesNotMatch(source, /@import\s+url\(['"]?https?:\/\//)
}
console.log('PASS: r16 Vitesse UI responsive/light-dark/a11y, Feathers-Pinia selectors and licensed design reference boundary')
