import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = file => readFileSync(new URL(file, import.meta.url), 'utf8')
const service = read('../server/services/notes/notes.service.ts')
const serviceClass = read('../server/services/notes/notes.class.ts')
const store = read('../src/feathers/services/notes/store.ts')
const page = read('../src/pages/feathers.vue')
const client = read('../src/lib/feathers-client.ts')
const schema = read('../shared/feathers/notes.schema.ts')
for (const operation of ['find', 'get', 'create', 'patch', 'remove'])
  assert.ok(serviceClass.includes(`async ${operation}(`), `Missing ${operation}`)
assert.ok(service.includes('.publish('))
assert.ok(service.includes("channel('demo-notes')"))
for (const event of ['created', 'patched', 'removed']) assert.ok(schema.includes(`'${event}'`))
assert.match(store, /api\.service\.on\(event, listener\)/)
assert.match(store, /api\.service\.off\(event, listener\)/)
assert.match(client, /client\.configure\(socketio\(socket\)\)/)
assert.match(page, /useNotesStore\(\)/)
assert.doesNotMatch(page, /socket\.emit\(/)
console.log('PASS: Feathers Pinia realtime source contract (network E2E tested separately)')
